import { Fragment, useEffect, useRef, useState } from 'react';
import clsx from 'clsx';
import { Send, Trash2 } from 'lucide-react';
import {
  useAssistantHistory,
  useAssistantStatus,
  useSendMessage,
  useConfirmAction,
  useCancelAction,
  useClearHistory,
} from '../../api/hooks.js';
import { useToast } from '../../components/ui/toast.jsx';
import { Button } from '../../components/ui/primitives.jsx';
import { LogoMark } from '../../components/brand/Logo.jsx';
import { timeOfDay } from '../../lib/format.js';
import { ActionCard } from './ActionCard.jsx';
import { MessageData } from './MessageData.jsx';

export const SUGGESTIONS = [
  'How much did I spend this month?',
  'Where is my money going?',
  'Compare this month with last month',
  'Am I over budget anywhere?',
  'Any unusual spending?',
  'Spent 450 on groceries yesterday',
];

/** Renders **bold** and line breaks from a reply; everything else is plain text. */
function RichText({ text }) {
  return text.split('\n').map((line, i) => (
    <Fragment key={i}>
      {i > 0 && <br />}
      {line.split(/(\*\*[^*]+\*\*)/g).map((part, j) =>
        part.startsWith('**') && part.endsWith('**') ? (
          <strong key={j} className="font-semibold">
            {part.slice(2, -2)}
          </strong>
        ) : (
          <Fragment key={j}>{part}</Fragment>
        ),
      )}
    </Fragment>
  ));
}

export function EngineBadge({ status }) {
  if (!status) return null;
  const gemini = status.provider === 'gemini';
  return (
    <span
      className={clsx(
        'inline-flex items-center gap-1.5 rounded-full px-2.5 py-1 text-[0.75rem] font-medium',
        gemini ? 'bg-brand-soft text-brand' : 'bg-surface-2 text-ink-2',
      )}
      title={gemini ? `Answers are generated by Google Gemini (${status.model})` : 'Gemini is not configured; using the built-in offline engine'}
    >
      <span aria-hidden className={clsx('h-1.5 w-1.5 rounded-full', gemini ? 'bg-income' : 'bg-ink-3')} />
      {gemini ? `Gemini ${status.model?.replace(/^gemini-/, '') ?? ''}`.trim() : 'Offline mode'}
    </span>
  );
}

function Message({ message, onConfirm, onCancel, busyId }) {
  const mine = message.role === 'user';
  if (mine) {
    return (
      <li className="flex justify-end">
        <div
          className={clsx(
            'max-w-[85%] rounded-2xl rounded-br-md bg-brand px-4 py-2.5 text-[0.9375rem] text-brand-ink',
            message.pending && 'opacity-70',
          )}
        >
          {message.content}
          {message.failed && <p className="mt-1 text-[0.8125rem] opacity-90">Not sent. Check the server and try again.</p>}
        </div>
      </li>
    );
  }
  return (
    <li className="flex gap-3">
      <LogoMark size={28} className="mt-0.5 shrink-0" />
      <div className="min-w-0 flex-1">
        <div className="text-[0.9375rem] leading-relaxed text-ink">
          <RichText text={message.content} />
        </div>
        <MessageData data={message.data} />
        {message.pendingAction && (
          <ActionCard
            action={message.pendingAction}
            busy={busyId === message.id}
            onConfirm={() => onConfirm(message.id)}
            onCancel={() => onCancel(message.id)}
          />
        )}
        <p className="mt-1.5 text-[0.75rem] text-ink-3">{timeOfDay(message.createdAt)}</p>
      </div>
    </li>
  );
}

/** Conversation with Kosha Copilot: used on the Copilot page and in the drawer. */
export function CopilotChat({ compact = false, className }) {
  const { data: history = [], isLoading } = useAssistantHistory();
  const { data: status } = useAssistantStatus();
  const send = useSendMessage();
  const confirm = useConfirmAction();
  const cancel = useCancelAction();
  const clear = useClearHistory();
  const toast = useToast();
  const [text, setText] = useState('');
  const [busyId, setBusyId] = useState(null);
  const listRef = useRef(null);

  useEffect(() => {
    listRef.current?.scrollTo({ top: listRef.current.scrollHeight, behavior: 'smooth' });
  }, [history.length, send.isPending]);

  const submit = (value) => {
    const message = value.trim();
    if (!message || send.isPending) return;
    setText('');
    send.mutate(message, { onError: (err) => toast.error(err.message) });
  };

  const resolve = (mutation, verb) => (id) => {
    setBusyId(id);
    mutation.mutate(id, {
      onSuccess: () => toast.success(verb === 'confirm' ? 'Saved' : 'Draft discarded'),
      onError: (err) => toast.error(err.message),
      onSettled: () => setBusyId(null),
    });
  };

  return (
    <div className={clsx('flex min-h-0 flex-col', className)}>
      <div className="flex items-center justify-between gap-3 border-b border-line px-4 py-3 sm:px-5">
        <div className="flex items-center gap-2">
          <h2 className="font-wide font-semibold">Copilot</h2>
          <EngineBadge status={status} />
        </div>
        {history.length > 0 && (
          <Button variant="ghost" size="sm" onClick={() => clear.mutate()} disabled={clear.isPending}>
            <Trash2 size={15} aria-hidden />
            Clear chat
          </Button>
        )}
      </div>

      <ul ref={listRef} className="flex flex-1 flex-col gap-5 overflow-y-auto px-4 py-5 scrollbar-thin sm:px-5" aria-live="polite">
        {!isLoading && history.length === 0 && (
          <li className="my-auto">
            <p className={clsx('font-wide font-semibold', compact ? 'text-lg' : 'text-xl')}>Ask about your money</p>
            <p className="mt-1 max-w-md text-sm text-ink-2">
              Copilot reads your Kosha data to answer, and can draft transactions or budgets for you to confirm.
            </p>
            <div className="mt-4 flex flex-wrap gap-2">
              {SUGGESTIONS.slice(0, compact ? 4 : 6).map((s) => (
                <button
                  key={s}
                  type="button"
                  onClick={() => submit(s)}
                  className="rounded-full bg-surface px-3.5 py-2 text-left text-sm text-ink ring-1 ring-line-strong hover:bg-surface-2"
                >
                  {s}
                </button>
              ))}
            </div>
          </li>
        )}
        {history.map((m) => (
          <Message key={m.id} message={m} busyId={busyId} onConfirm={resolve(confirm, 'confirm')} onCancel={resolve(cancel, 'cancel')} />
        ))}
        {send.isPending && (
          <li className="flex items-center gap-3" aria-label="Copilot is thinking">
            <LogoMark size={28} />
            <span className="flex gap-1">
              {[0, 1, 2].map((i) => (
                <span key={i} className="typing-dot h-2 w-2 rounded-full bg-ink-3" />
              ))}
            </span>
          </li>
        )}
      </ul>

      <form
        className="border-t border-line p-3 sm:p-4"
        onSubmit={(e) => {
          e.preventDefault();
          submit(text);
        }}
      >
        <div className="flex items-end gap-2 rounded-xl bg-surface p-1.5 ring-1 ring-line-strong focus-within:ring-2 focus-within:ring-brand">
          <label htmlFor={compact ? 'copilot-input-drawer' : 'copilot-input'} className="sr-only">
            Message Copilot
          </label>
          <textarea
            id={compact ? 'copilot-input-drawer' : 'copilot-input'}
            rows={1}
            value={text}
            maxLength={500}
            onChange={(e) => setText(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === 'Enter' && !e.shiftKey) {
                e.preventDefault();
                submit(text);
              }
            }}
            placeholder='Try "How did I do in October?" or "Spent 300 on Uber"'
            className="max-h-32 min-h-10 flex-1 resize-none bg-transparent px-2.5 py-2 text-[0.9375rem] placeholder:text-ink-3 focus:outline-none"
          />
          <Button type="submit" size="icon" aria-label="Send" disabled={!text.trim() || send.isPending} className="h-10 w-10">
            <Send size={17} />
          </Button>
        </div>
      </form>
    </div>
  );
}
